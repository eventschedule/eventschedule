    <section id="the-tab" class="doc-section">
        <h2 class="doc-heading">
            <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="w-5 h-5 text-gray-500 dark:text-gray-400 flex-shrink-0">
                <path stroke-linecap="round" stroke-linejoin="round" d="M9 6.75V15m6-6v8.25m.503 3.498l4.875-2.437c.381-.19.622-.58.622-1.006V4.82c0-.836-.88-1.38-1.628-1.006l-3.869 1.934c-.317.159-.69.159-1.006 0L9.503 3.252a1.125 1.125 0 00-1.006 0L3.622 5.689C3.24 5.88 3 6.27 3 6.695V19.18c0 .836.88 1.38 1.628 1.006l3.869-1.934c.317-.159.69-.159 1.006 0l4.994 2.497c.317.158.69.158 1.006 0z" />
            </svg>
            The Vendor map tab
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">Everything about the market happens on the schedule's <strong class="text-gray-900 dark:text-white">Vendor map</strong> tab. The number beside its name counts the vendors waiting for your answer. Owners and admins of the schedule see it.</p>

        <x-doc-screenshot id="vendor-maps--tab" alt="The Vendor map tab: the For your vendors and For shoppers cards, the market days, the map, and two requests for the same spot" />

        <h3 class="doc-subheading">The two cards</h3>

        <div class="doc-fields">
            <div class="doc-field">
                <h4>For your vendors</h4>
                <p>The vendor link and the message that goes with it, with <strong>Copy link</strong> and <strong>Send on WhatsApp</strong>. <strong>Vendors can join with this link</strong> opens and closes it, and <strong>Make a new link</strong> replaces it, after which the old one stops working. See <a href="#vendor-link" class="doc-link">Sending the vendor link</a>.</p>
            </div>
            <div class="doc-field">
                <h4>For shoppers</h4>
                <p>How many spots have a name (shoppers see the rest as empty), <strong>See what shoppers see</strong>, <strong>Copy link</strong>, <strong>Put the map on your website</strong> and <strong>Print the entrance sign</strong>. See <a href="#shoppers" class="doc-link">What shoppers see</a>.</p>
            </div>
        </div>

        <h3 class="doc-subheading">The market day</h3>

        <p class="text-gray-600 dark:text-gray-300 mb-4">Below the cards, the coming market days run along the top. Pick one and the map shows that day: how many vendors are <strong class="text-gray-900 dark:text-white">coming</strong>, how many are <strong class="text-gray-900 dark:text-white">not coming</strong>, how many spots are <strong class="text-gray-900 dark:text-white">empty</strong>, and how many requests are <strong class="text-gray-900 dark:text-white">waiting for you</strong>. Tap a spot to see who is on it, with their phone number when they gave one, a WhatsApp button and a link to their page. <strong class="text-gray-900 dark:text-white">Edit the map</strong> opens the designer.</p>

        <h3 class="doc-subheading">Reviewing requests</h3>

        <p class="text-gray-600 dark:text-gray-300 mb-4">Requests from the vendor link wait under <strong class="text-gray-900 dark:text-white">Waiting for you</strong> (on a phone, one at a time). Each shows the vendor's name, what they sell, the spot they asked for and the days they want. Two warnings can appear on a request: <strong class="text-gray-900 dark:text-white">Two vendors want this spot</strong>, and <strong class="text-gray-900 dark:text-white">The name they typed is not the name on the spot</strong>.</p>

        <ul class="doc-list mb-6">
            <li><strong class="text-gray-900 dark:text-white">Approve</strong> puts them on the spot. A short notice offers <strong class="text-gray-900 dark:text-white">Tell them on WhatsApp</strong>, and <strong class="text-gray-900 dark:text-white">Undo</strong> while it shows.</li>
            <li><strong class="text-gray-900 dark:text-white">Decline</strong> can carry a note for the vendor.</li>
            <li><strong class="text-gray-900 dark:text-white">Move to...</strong> gives them a different spot than the one they asked for.</li>
            <li><strong class="text-gray-900 dark:text-white">Approve all without conflicts</strong> approves every request in one press except those where two vendors want the same spot, which are left for you to decide.</li>
        </ul>

        <p class="text-gray-600 dark:text-gray-300 mb-4">Approved vendors are emailed with their spot marked on the map, and with a link to say when they cannot come. You are emailed when vendors are waiting or cannot come, gathered into one message.</p>

        <h3 class="doc-subheading">Changes for one day, or from now on</h3>

        <div class="doc-fields">
            <div class="doc-field">
                <h4>Move a vendor</h4>
                <p>Tap their spot, choose <strong>Move to...</strong> and tap the new spot. Then choose <strong>This day only</strong>, or <strong>From now on</strong> for the rest of the season. Moving a vendor onto someone else's spot offers to swap the two.</p>
            </div>
            <div class="doc-field">
                <h4>Not coming</h4>
                <p>Marks a vendor absent on the day you are looking at. Shoppers see "Not here today" on that spot for that date only. <strong>Coming after all</strong> takes it back. Vendors can mark it themselves.</p>
            </div>
            <div class="doc-field">
                <h4>Add a vendor for this day</h4>
                <p>Tap an empty spot to put someone on it for that one date: a name and what they sell, no account needed. A vendor you added by hand can be removed with <strong>Remove</strong>.</p>
            </div>
            <div class="doc-field">
                <h4>Cancel this day</h4>
                <p>Rained off, a holiday, anything else: choose why and confirm. The shoppers' map says there is no market that day, with the reason. For a market that repeats every week the date also comes off the calendar. A one-day or multi-day event (a fair, an expo) is called off on the map only: the event itself stays as it is, and cancelling it, with the email to anyone holding a ticket, is still done from the event.</p>
            </div>
            <div class="doc-field">
                <h4>Open this day again</h4>
                <p>A cancelled day reads <strong>Cancelled</strong> on the tab, with <strong>Open this day again</strong> beside it. Press it when the day goes ahead after all: the shoppers' map shows the market again, and a weekly market's date is back on the calendar.</p>
            </div>
        </div>

        <p class="text-gray-600 dark:text-gray-300 mb-6">Under <strong class="text-gray-900 dark:text-white">Settings</strong> at the foot of the tab you can change the map's kind, choose which event it is for, and draft the map again from photos.</p>
    </section>

