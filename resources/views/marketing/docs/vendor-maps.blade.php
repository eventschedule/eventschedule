    <!-- Turning it on -->
    <section id="turning-it-on" class="doc-section">
        <h2 class="doc-heading">
            <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="w-5 h-5 text-gray-500 dark:text-gray-400 flex-shrink-0">
                <path stroke-linecap="round" stroke-linejoin="round" d="M5.636 5.636a9 9 0 1012.728 0M12 3v9" />
            </svg>
            Turning it on
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">A vendor map is a plan of a market, a fair or an expo: every <strong class="text-gray-900 dark:text-white">spot</strong> (a stall, a table, a stand or a booth) and who is standing at it on each date. It belongs to a <strong class="text-gray-900 dark:text-white">venue</strong> schedule, which has one map, and it serves one of that schedule's events: usually the weekly market day, or the dates of the fair.</p>

        <p class="text-gray-600 dark:text-gray-300 mb-4">Vendors on the map are not the event's participants. They live on the map, date by date, so a vendor who comes every week, one who comes once, and one who cannot make it this Saturday are all kept apart without touching the event itself.</p>

        <div class="doc-callout doc-callout-info mb-6">
            <div class="doc-callout-title">Not the venue map</div>
            <p>The <strong>vendor map</strong> is a plan you draw of one market. It is a different thing from the map of venues on a street map that a schedule's page can show.</p>
        </div>

        <h3 class="doc-subheading">Starting a map</h3>

        <ul class="doc-list mb-6">
            <li><strong class="text-gray-900 dark:text-white">With a new schedule.</strong> Where you choose what kind of schedule to make, choose <strong class="text-gray-900 dark:text-white">Venue</strong>, turn on <strong class="text-gray-900 dark:text-white">Running a market, fair or expo?</strong> under it and press <strong class="text-gray-900 dark:text-white">Continue with venue</strong>. It opens the form for a venue schedule, and once you save it you land on the schedule's <strong class="text-gray-900 dark:text-white">Vendor map</strong> tab, ready to set the map up.</li>
            <li><strong class="text-gray-900 dark:text-white">With a schedule you already have.</strong> Every venue schedule has a <strong>Vendor map</strong> tab in the admin panel, beside Seating plans. Open it to start the venue's first map.</li>
        </ul>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The tab first asks two quick questions:</p>

        <div class="doc-fields">
            <div class="doc-field">
                <h4>What is it?</h4>
                <p>A farmers market, a craft fair, a flea market, a food festival, or a conference or expo. The choice sets the words every screen uses (a stall, a table, a stand or a booth), and you can change it later under <strong>Settings</strong> at the foot of the tab.</p>
            </div>
            <div class="doc-field">
                <h4>Which of your events is it?</h4>
                <p>Pick an event the schedule already runs, or <strong>A new one</strong>. For a new one, give it a name and say <strong>Which days?</strong> (the days of the week it runs, the hours, the first day and whether it is <strong>Every week</strong>), or for an expo <strong>Which dates?</strong> (its first and last day). Then press <strong>Continue</strong>, and the event is created for you.</p>
            </div>
        </div>

        <p class="text-gray-600 dark:text-gray-300 mb-6">Next comes the map itself: draft it from photos, or press <strong class="text-gray-900 dark:text-white">Draw it myself</strong>.</p>
    </section>

    <!-- Drafting from photos -->
    <section id="drafting-from-photos" class="doc-section">
        <h2 class="doc-heading">
            <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="w-5 h-5 text-gray-500 dark:text-gray-400 flex-shrink-0">
                <path stroke-linecap="round" stroke-linejoin="round" d="M6.827 6.175A2.31 2.31 0 015.186 7.23c-.38.054-.757.112-1.134.175C2.999 7.58 2.25 8.507 2.25 9.574V18a2.25 2.25 0 002.25 2.25h15A2.25 2.25 0 0021.75 18V9.574c0-1.067-.75-1.994-1.802-2.169a47.865 47.865 0 00-1.134-.175 2.31 2.31 0 01-1.64-1.055l-.822-1.316a2.192 2.192 0 00-1.736-1.039 48.774 48.774 0 00-5.232 0 2.192 2.192 0 00-1.736 1.039l-.821 1.316z M16.5 12.75a4.5 4.5 0 11-9 0 4.5 4.5 0 019 0z" />
            </svg>
            Drafting the map from photos <x-doc-badge plan="pro" />
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">On <strong class="text-gray-900 dark:text-white">Make your map from photos</strong>, take a few photos of the market (<strong class="text-gray-900 dark:text-white">Take photos now</strong>) or choose them from your phone or computer (<strong class="text-gray-900 dark:text-white">Upload photos or your printed map</strong>), up to 20 photos for each area and one PDF. A place with several parts, such as a covered hall and a few outdoor sections, is best photographed area by area: once you have photos, name the first area and press <strong class="text-gray-900 dark:text-white">Add another area</strong> for the next. The AI maps each area on its own, and the map opens with each area as a block you drag by its name to where it really is. If there is anything the AI should know, such as which side the covered hall is on or where the numbers start, write it under <strong class="text-gray-900 dark:text-white">Anything the AI should know?</strong>. Then press <strong class="text-gray-900 dark:text-white">Make my map</strong>.</p>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The AI finds the spots, groups them into areas and reads the names on the vendors' signs. It takes about a minute, and you can leave the page: your map will be there when you come back. Three things make a better draft:</p>

        <ul class="doc-list mb-4">
            <li><strong class="text-gray-900 dark:text-white">Stand somewhere high.</strong> A step, a balcony or a first-floor window shows more of the ground, and the layout comes out truer.</li>
            <li><strong class="text-gray-900 dark:text-white">Get a whole row in each photo.</strong> A row cut across two photos is harder to count.</li>
            <li><strong class="text-gray-900 dark:text-white">Make sure the signs can be read.</strong> The names come from the vendors' own signs.</li>
        </ul>

        <div class="doc-callout doc-callout-info mb-6">
            <div class="doc-callout-title">What to expect</div>
            <p>A photo from above, or the map you already print (a PDF or a photo of it), gives a near-final map. Photos from the aisles give a rough layout and the vendors' names. Either way the designer opens with the draft, and <strong>Check the names</strong> lists the names the AI was least sure of first: fix one, or clear it to leave the spot unnamed, and press <strong>Looks right, save</strong>.</p>
        </div>

        <p class="text-gray-600 dark:text-gray-300 mb-6">Drafting from photos is part of Pro <x-doc-badge plan="pro" />, and each photo counts against the daily AI allowance. A selfhosted install offers it once a Gemini API key is set. You can draft the map again at any time from <strong class="text-gray-900 dark:text-white">Make the map again from photos</strong> under Settings; you are asked before the new draft replaces the map you have.</p>
    </section>

