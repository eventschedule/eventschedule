    <section id="shoppers" class="doc-section">
        <h2 class="doc-heading">
            <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="w-5 h-5 text-gray-500 dark:text-gray-400 flex-shrink-0">
                <path stroke-linecap="round" stroke-linejoin="round" d="M15.75 10.5V6a3.75 3.75 0 10-7.5 0v4.5m11.356-1.993l1.263 12c.07.665-.45 1.243-1.119 1.243H4.25a1.125 1.125 0 01-1.12-1.243l1.264-12A1.125 1.125 0 015.513 7.5h12.974c.576 0 1.059.435 1.119 1.007zM8.625 10.5a.375.375 0 11-.75 0 .375.375 0 01.75 0zm7.5 0a.375.375 0 11-.75 0 .375.375 0 01.75 0z" />
            </svg>
            What shoppers see
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The map has a page of its own at your schedule's address followed by <code>/map</code>, which <strong class="text-gray-900 dark:text-white">See what shoppers see</strong> opens. It shows the next market day: the map with each spot's number and name, and the list of who is here, area by area. Shoppers search by a vendor's name or by what they sell, filter by category, and tap a vendor to see what they sell and to visit their page. A vendor who is not coming shows "Not here today", and a cancelled day says the market is closed and why.</p>

        <x-doc-screenshot id="vendor-maps--map-page" alt="The shoppers' map page: a search box, category buttons and the list of who is here beside the map of the market" />

        <h3 class="doc-subheading">The entrance sign</h3>

        <p class="text-gray-600 dark:text-gray-300 mb-4"><strong class="text-gray-900 dark:text-white">Print the entrance sign</strong> opens an A4 sign with the market's name, the whole map, "You are here" where you placed it, and a large QR code to scan with a phone camera. <strong class="text-gray-900 dark:text-white">Print</strong> prints it; <strong class="text-gray-900 dark:text-white">Download the sign (image)</strong> gives a 300 dpi picture for a print shop. Scanning the code opens the map with "You are here" marked.</p>

