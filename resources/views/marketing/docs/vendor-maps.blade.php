    <section id="drawing" class="doc-section">
        <h2 class="doc-heading">
            <svg aria-hidden="true" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="w-5 h-5 text-gray-500 dark:text-gray-400 flex-shrink-0">
                <path stroke-linecap="round" stroke-linejoin="round" d="M16.862 4.487l1.687-1.688a1.875 1.875 0 112.652 2.652L10.582 16.07a4.5 4.5 0 01-1.897 1.13L6 18l.8-2.685a4.5 4.5 0 011.13-1.897l8.932-8.931zm0 0L19.5 7.125M18 14v4.75A2.25 2.25 0 0115.75 21H5.25A2.25 2.25 0 013 18.75V8.25A2.25 2.25 0 015.25 6H10" />
            </svg>
            Drawing and editing the map
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The designer opens from <strong class="text-gray-900 dark:text-white">Edit the map</strong> on the Vendor map tab, or from <strong class="text-gray-900 dark:text-white">Draw it myself</strong> when the map is new. On a computer the map is in the middle and a panel sits beside it; on a phone the same tools are along the top and the panel opens as a sheet from the bottom. Drag a spot to move it, and tap it to change its number, its name or its area. <strong class="text-gray-900 dark:text-white">Save</strong> stores the map; until then nothing you change reaches the vendors or the shoppers.</p>

        <x-doc-screenshot id="vendor-maps--designer" alt="The map designer with a hall of numbered rows, a second area of single spots, food trucks, a crafts corner and the entrance" />

        <div class="doc-fields">
            <div class="doc-field">
                <h4>Add a row</h4>
                <p>Several spots side by side in one go. Say <strong>How many</strong>, the <strong>First number</strong>, and whether they are numbered <strong>From the left</strong> or <strong>From the right</strong>.</p>
            </div>
            <div class="doc-field">
                <h4>Add a spot</h4>
                <p>One spot, anywhere. A market in a field or a square is rarely a grid, so place each spot where it stands, then set its <strong>Width</strong> and <strong>Depth</strong> and <strong>Turn</strong> it to match. <strong>Duplicate</strong> makes another just like it.</p>
            </div>
            <div class="doc-field">
                <h4>Number in order</h4>
                <p>Tap the spots in the order people walk past them, and they are numbered in that order. The note at the top says which number comes next; press <strong>Done</strong> when you are finished.</p>
            </div>
            <div class="doc-field">
                <h4>Areas</h4>
                <p>Group spots into named areas, each with its own colour: the covered hall, the food trucks, the crafts corner. Shoppers see the areas on the map and in the list.</p>
            </div>
            <div class="doc-field">
                <h4>Add a landmark</h4>
                <p>The <strong>Entrance</strong>, <strong>Restrooms</strong>, <strong>Parking</strong>, a <strong>Stage</strong>, or a <strong>Label</strong> with any text. Landmarks are never a spot: nobody can claim one.</p>
            </div>
            <div class="doc-field">
                <h4>You are here</h4>
                <p>Under Add a landmark. Tap where the entrance sign will hang, and the map opened from that sign's QR code shows "You are here" at that point.</p>
            </div>
            <div class="doc-field">
                <h4>Undo</h4>
                <p>Takes back the last change, one step at a time.</p>
            </div>
            <div class="doc-field">
                <h4>Show the photo</h4>
                <p>On a map drafted from photos, shows the photo under the map so you can trace over it, as strongly as you like.</p>
            </div>
        </div>

        <ul class="doc-list mb-6">
            <li><strong class="text-gray-900 dark:text-white">Renumbering is safe.</strong> When a save changes the numbers of spots that have vendors, you are told how many, and each vendor sees the new number on their own page.</li>
            <li><strong class="text-gray-900 dark:text-white">A spot with a vendor for the season cannot be removed.</strong> Move the vendor first, then remove the spot.</li>
            <li><strong class="text-gray-900 dark:text-white">Two people editing at once.</strong> If someone else saved the map while you were working, you are told, your changes are kept, and you choose whether to save yours over theirs.</li>
        </ul>
    </section>

