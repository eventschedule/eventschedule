            </svg>
            Sending the vendor link <x-doc-badge plan="pro" />
        </h2>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The vendor link is one address for all your vendors. On the <strong class="text-gray-900 dark:text-white">For your vendors</strong> card, edit the message if you like and press <strong class="text-gray-900 dark:text-white">Send on WhatsApp</strong>: WhatsApp opens with the message ready to send to your vendors' group. <strong class="text-gray-900 dark:text-white">Copy link</strong> gives you the address for anywhere else.</p>

        <x-doc-screenshot id="vendor-maps--vendor-link" alt="The vendor link on a phone: Is one of these you?, a search by name or number, and the map of spots to tap" />

        <h3 class="doc-subheading">What vendors see</h3>

        <ol class="doc-list mb-6">
            <li><strong class="text-gray-900 dark:text-white">Is one of these you?</strong> The spots, as a list or on the map, with the names the map already has. They search by name or number and tap their own spot. A spot someone has already asked for says so.</li>
            <li><strong class="text-gray-900 dark:text-white">About you.</strong> Their name at the market, what they sell (tap one or two categories, and a line of their own if they like), a photo shoppers will see once you approve, and a phone number that only you see. They choose <strong class="text-gray-900 dark:text-white">Every market day</strong> or particular dates.</li>
            <li><strong class="text-gray-900 dark:text-white">So only you can change it.</strong> They confirm with a 6-digit code sent to their email, or with Google. Nobody sets a password. Inside Instagram or Facebook, where Google sign-in does not work, they are offered to open the page in their browser or to use their email.</li>
            <li><strong class="text-gray-900 dark:text-white">Sent.</strong> The request waits for you, and they hear when it is confirmed.</li>
        </ol>

        <p class="text-gray-600 dark:text-gray-300 mb-4">The same link is their home afterwards. Opening it again shows their spot, their coming dates, <strong class="text-gray-900 dark:text-white">Not coming</strong> for any one of them (you are told, and their spot reads "Not here today"), <strong class="text-gray-900 dark:text-white">Change what you sell</strong>, <strong class="text-gray-900 dark:text-white">Share where to find me</strong> to post their spot to their own followers, and <strong class="text-gray-900 dark:text-white">Stop coming</strong>, which frees the spot for the rest of the season. Each vendor also gets a page of their own on Event Schedule, which shoppers reach from the map.</p>

        <div class="doc-callout doc-callout-plan mb-6">
            <div class="doc-callout-title">If Pro ends <x-doc-badge plan="pro" /></div>
            <p>The vendor link is a Pro feature of the map's schedule; vendors never need a plan. If the schedule leaves Pro, the vendors you approved stay on the map and Not coming keeps working, but the link stops taking new requests. On a selfhosted install, vendors can join only while new accounts are allowed (<code>ALLOW_REGISTRATION</code>), and the tab says so when they are not.</p>
        </div>
    </section>

